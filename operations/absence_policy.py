"""
operations/absence_policy.py — عتبات الغياب كما نصّت عليها الوزارة.

المصدر: «الدليل التعريفي لسياسة تقييم الطلبة» الصادر عن هيئة التقييم بوزارة
التعليم والتعليم العالي، استناداً إلى القرار الوزاري رقم (22) لسنة 2015
باعتماد سياسات تقييم الطلبة — صفحة 27 للصفوف ٤–١١، وصفحة 37 للصف الثاني عشر.

وقبل هذه الوحدة كانت المنصّة تحسب «10٪ من أيام الدراسة (≈19 يوماً من 190)»
وتنسبها إلى **المادة 7 من قانون التعليم الإلزامي 25/2001**. وقد راجعتُ نصّ
القانون كاملاً: مادّته السابعة توجب على المدرسة إخطار المسؤول عن الطفل بكتابٍ
مسجَّل، ولا تذكر نسبةً ولا عدد أيام — لا هي ولا سائر مواده الثلاث عشرة.
فالإحالة كانت خاطئة، والرقم مُخترعاً، والوحدة مغلوطة.

والفروق كلّها:

    الوحدة      حصصاً                →  أيام تمدرس
    العتبة      10٪ ≈ 19            →  7 · 10 · 13 · 15
    العدد       واحدة                →  أربع (وللثاني عشر اثنتان)
    النطاق      نافذة العام          →  تراكميّ من بداية العام
    الأثر       تنبيه وليّ الأمر      →  حرمانٌ من دخول الاختبار

وهذه الوحدة **تحسب ولا تُنفّذ**. حرمانُ طالبٍ من اختباره قرارٌ بشريّ، وخطأٌ
في يومٍ واحد يمنع طالباً من حقّه. فالمنصّة تعرض الموقف وتُنذر، والقرار لأهله.

تحفّظ: الدليل صادر 2018. وقبل أيّ إنفاذٍ آليّ يلزم تأكيدٌ من قسم شؤون
الاختبارات أن الأرقام لم تُعدَّل للعام الجاري.
"""

from __future__ import annotations

from dataclasses import dataclass

#: نطاقات الصفوف كما تُصنّفها السياسة — لا كما تُصنّفها نوافذ الاختبارات.
BAND_4_11 = "g4_11"
BAND_12 = "g12"
BAND_UNKNOWN = ""


@dataclass(frozen=True)
class Gate:
    """عتبةٌ واحدة: تجاوزها يحرم من اختبارٍ بعينه."""

    key: str
    label: str
    #: يُحرم من **تجاوز** هذا العدد — فالمساواة به لا تحرم.
    max_days: int
    event_type: str
    semester: str


#: الصفوف من الرابع إلى الحادي عشر — الدليل ص 27.
GATES_4_11: tuple[Gate, ...] = (
    Gate("s1_midterm", "اختبار منتصف الفصل الأول", 7, "midterm_exam", "S1"),
    Gate("s1_final", "اختبار نهاية الفصل الأول", 10, "final_exam", "S1"),
    Gate("s2_midterm", "اختبار منتصف الفصل الثاني", 13, "midterm_exam", "S2"),
    Gate("first_round", "اختبار الدور الأول", 15, "final_exam", "S2"),
)

#: الصف الثاني عشر — الدليل ص 37. عتبتان لا أربع.
GATES_12: tuple[Gate, ...] = (
    Gate("s1_final", "اختبار نهاية الفصل الأول", 10, "final_exam", "S1"),
    Gate("s2_final", "اختبار نهاية الفصل الثاني", 15, "final_exam", "S2"),
)

#: أنواع الأعذار المقبولة — الدليل ص 28 و38.
ACCEPTED_EXCUSES = (
    "المرض، ويثبت بشهادة طبية معتمدة من الجهات الحكومية المختصة",
    "الحوادث الطارئة والظروف القهرية التي لا يمكن دفعها",
    "المهمات الرسمية المؤيدة بشهادة من جهة العمل",
)

#: آخر موعدٍ لإثبات العذر: اليوم الثالث بعد انتهاء جدول الاختبار (ص 28 و38).
EXCUSE_PROOF_DEADLINE_DAYS = 3


def band_for(grade) -> str:
    """يُحوّل الصفّ إلى نطاق السياسة.

    الصفوف ١–٣ لها قسمٌ مستقلّ في الدليل لم يُشفَّر هنا — والمنصّة إعدادية
    وثانوية. وإرجاع نطاقٍ مجهولٍ أصدق من تطبيق جدولٍ لا يخصّها.
    """
    digits = "".join(ch for ch in str(grade) if ch.isdigit())
    if not digits:
        return BAND_UNKNOWN
    number = int(digits)
    if number == 12:
        return BAND_12
    if 4 <= number <= 11:
        return BAND_4_11
    return BAND_UNKNOWN


def gates_for(grade) -> tuple[Gate, ...]:
    """عتبات الصفّ مرتّبةً تصاعدياً — وفارغةٌ لمن لا جدول له."""
    band = band_for(grade)
    if band == BAND_12:
        return GATES_12
    if band == BAND_4_11:
        return GATES_4_11
    return ()


def next_gate(grade, unexcused_days: int) -> Gate | None:
    """أوّل عتبةٍ لم تُتجاوز بعد — أو `None` إن تُجوِّزت كلّها."""
    for gate in gates_for(grade):
        if unexcused_days <= gate.max_days:
            return gate
    return None


def breached(grade, unexcused_days: int) -> tuple[Gate, ...]:
    """العتبات المتجاوَزة — أي الاختبارات التي يقع صاحبها تحت طائلة الحرمان."""
    return tuple(g for g in gates_for(grade) if unexcused_days > g.max_days)
