def band_for(grade, ese: bool = False) -> str:
    """يُحوّل الصفّ إلى نطاق السياسة.

    و`ese` علمٌ صريحٌ لا يُشتقّ من الصفّ: طالبُ التربية الخاصّة في الثامن
    صفُّه ثامنٌ وسلّمُه سلّمُ 3.7.3.3 — فلا يُعرف من رقم الصفّ وحدَه.

    والصفوف 1–3 لها في الدليل قسمٌ لم يُشفَّر هنا، والمنصّةُ إعداديّةٌ
    وثانويّة. وإرجاعُ نطاقٍ مجهولٍ أصدقُ من تطبيق جدولٍ لا يخصّها.
    """
    if ese:
        return BAND_ESE
    digits = "".join(ch for ch in str(grade) if ch.isdigit())
    if not digits:
        return BAND_UNKNOWN
    number = int(digits)
    if number == 12:
        return BAND_12
    if 1 <= number <= 11:
        return BAND_1_11
    return BAND_UNKNOWN


def gates_for(grade, ese: bool = False) -> tuple[Gate, ...]:
    """عتبات الصفّ مرتّبةً تصاعدياً — وفارغةٌ لمن لا جدول له."""
    return {
        BAND_ESE: GATES_ESE,
        BAND_12: GATES_12,
        BAND_1_11: GATES_1_11,
    }.get(band_for(grade, ese), ())


def next_gate(grade, unexcused_days: int, ese: bool = False) -> Gate | None:
    """أوّل عتبةٍ لم تُتجاوز بعد — أو `None` إن تُجوِّزت كلّها."""
    for gate in gates_for(grade, ese):
        if unexcused_days <= gate.max_days:
            return gate
    return None


def breached(grade, unexcused_days: int, ese: bool = False) -> tuple[Gate, ...]:
    """العتبات المتجاوَزة — أي الاختبارات التي يقع صاحبها تحت طائلة الحرمان."""
    return tuple(g for g in gates_for(grade, ese) if unexcused_days > g.max_days)


def absence_days_from_tardies(tardy_count: int) -> int:
    """أيّامُ الغياب التي يُنتجها التأخّرُ المتكرّر — كلُّ سبعٍ يومٌ واحد.

    السابعةُ يومٌ، والرابعةَ عشرةَ يومان. والقسمةُ لا العدُّ عند السبع: السلّمُ
    يُعاد من أوّله بعد كلّ احتساب في الممارسة، والدليلُ لا يقول إنّه يتوقّف —
    فمن تأخّر أربعةَ عشرَ مرّةً غاب يومين لا يوماً.
    """
    if tardy_count < 0:
        return 0
    return tardy_count // TARDIES_PER_ABSENCE_DAY


def tardy_step(tardy_count: int) -> str:
    """الإجراءُ المستحقُّ عند هذا التكرار — أو `""` إن لم يبلغ درجةً."""
    if tardy_count <= 0:
        return ""
    step = min(tardy_count, len(TARDY_LADDER))
    return TARDY_LADDER[step - 1][1]
