def ladder_text(code: str) -> list[tuple[int, str]]:
    """السلّمُ بصيغة (رقم الخطوة، نصّها) — الصيغةُ التي تقرؤها القوالبُ القائمة."""
    item = BY_CODE.get(code)
    if item is None:
        return []
    rows = []
    for number, step in enumerate(item.steps.steps, start=1):
        rows.append((number, " · ".join(f"{actor}: {action}" for actor, action in step)))
    if item.steps.beyond:
        rows.append((len(rows) + 1, f"ما بعد ذلك: {item.steps.beyond}"))
    return rows
