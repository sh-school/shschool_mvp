REFERRAL = "إحالةُ الطالب إلى قسم حماية ورعاية الطلبة لاتخاذ القرار المناسب وإشعارُ وليّ الأمر"


@dataclass(frozen=True)
class Ladder:
    """سلّمُ إجراءاتٍ لمخالفةٍ أو أكثر.

    `steps[i]` إجراءاتُ التكرار i+1: قائمةُ (الفاعل، الفعل) بترتيب الجدول.
    `beyond` ما يُفعل إذا تجاوز التكرارُ آخرَ السلّم — أو فارغٌ إن سكت الجدول.
    """

    key: str
    pages: str
    steps: tuple[tuple[tuple[str, str], ...], ...]
    beyond: str = ""
    notes: tuple[str, ...] = ()

    def step(self, repetition: int) -> tuple[tuple[str, str], ...]:
        """إجراءاتُ التكرار رقم `repetition` (يبدأ من 1)، وآخرُ درجةٍ لما بعدها."""
        index = max(1, min(repetition, len(self.steps))) - 1
        return self.steps[index]

    def is_beyond(self, repetition: int) -> bool:
        return repetition > len(self.steps)

    def to_json(self) -> dict[str, Any]:
        """تحويلُ السلّم إلى بنيةٍ قابلةٍ للتخزين في JSONB وإرجاعها للـAPI."""
        return {
            "ladder_key": self.key,
            "pages": self.pages,
            "max_reps": len(self.steps),
            "steps": [
                {
                    "rep": i + 1,
                    "actions": [{"actor": actor, "action": action} for actor, action in step],
                }
                for i, step in enumerate(self.steps)
            ],
            "beyond": self.beyond,
            "notes": list(self.notes),
        }


def _s(*pairs):
    return tuple(pairs)


