"""سقفٌ صريحٌ لحجم `custom.css` — نموٌّ يُراقَب لا نموٌّ صامت.

الملفُّ مصدرٌ واحدٌ لكلّ الهويّة البصريّة، فينمو مع كلّ ميزةٍ جديدة —
وهذا متوقَّعٌ ومقبول. لكن لا شيء حتى 2026-09-18 كان يُسقط البناء عند
تجاوزه حجماً بعينه، فالنموُّ يمرّ بصمتٍ حتى يُكتشَف في تدقيقٍ لاحق.

هذا ليس حظراً على النموّ، بل كابحاً له: تجاوزُ السقف قرارٌ يُرفع صراحةً
(رفعُ السقف نفسِه في هذا الملفّ) لا انزلاقٌ غيرُ مُلاحَظ. والسقفُ 400
كيلوبايت — هامشُ أمانٍ فوق 377 كيلوبايت (حجمُ الملفّ يومَ كتابة الحارس)
يُخفَّض تدريجياً بعد أيّ خطوة تصغير/ضغط فعليّة (خطّة إصلاح الهويّة
البصريّة، المرحلة 3).
"""

import pathlib

CSS_PATH = pathlib.Path("static/css/custom.css")

#: كيلوبايت = 1024 بايت هنا (لا 1000) — قياسُ حجم الملفّ على القرص لا الشبكة.
MAX_BYTES = 400 * 1024


def test_custom_css_stays_under_the_size_budget():
    size = CSS_PATH.stat().st_size
    assert size <= MAX_BYTES, (
        f"custom.css صار {size:,} بايت — يتجاوز السقف {MAX_BYTES:,} "
        "(400KB). إن كان النموّ مبرَّراً (ميزةٌ فعليّة لا تكرار) فارفع "
        "السقف هنا صراحةً مع سببٍ في رسالة الإيداع؛ لا تُسكِت الحارس بحذفه."
    )
