"""سقفٌ صريحٌ لحجم أنماط المنصّة **كما تصل المتصفّحَ** — نموٌّ يُراقَب لا نموٌّ صامت.

الأنماطُ مصدرٌ واحدٌ للهويّة البصريّة (ثمانيةُ ملفّاتٍ في `static/css/custom/`،
ADR-0003) فتنمو مع كلّ ميزةٍ جديدة — وهذا متوقَّعٌ ومقبول. لكن لا شيء حتى
2026-09-18 كان يُسقط البناءَ عند تجاوزها حجماً بعينه، فالنموُّ يمرّ بصمتٍ حتى
يُكتشَف في تدقيقٍ لاحق.

**يُقاس المنتَجُ المصغَّر لا المصدر** (قرارُ المالك 2026-09-19). كان السقفُ على المصدر
(400KB)، فصار يعاقب ما هو ممارسةٌ حسنة: التعليقاتُ العربيّة التي تبرّر القرارات
(ثلثا المصدر) وتوحيدُ التباعد بالرموز (`var(--sp-1-5)` أطولُ من `6px` في المصدر
وأثرُه على الشبكة +96 بايتاً بعد Brotli). فبلغ هامشُه 1.8KB بعد ترميز التباعد، وكان
الطلبُ التالي سيسقط لأنّه كتب تعليقاً. والمصغَّرُ هو ما ينزل فعلاً
(`core/static_storage.py` يصغّره وقتَ `collectstatic` في الإنتاج).

هذا ليس حظراً على النموّ، بل كابحاً له: تجاوزُ السقف قرارٌ يُرفع صراحةً
(رفعُ السقف نفسِه في هذا الملفّ) لا انزلاقٌ غيرُ مُلاحَظ.
"""

from tests.css_source import css_size, shipped_size

#: كيلوبايت = 1024 بايت. المصغَّرُ يومَ التحويل 228,749 بايت (86% من السقف)؛ والهامشُ
#: ≈31KB يكفي عدّةَ ميزاتٍ بلا أن يُنسى السقفُ. ويُخفَّض بعد أيّ تقليصٍ فعليّ.
MAX_SHIPPED_BYTES = 260 * 1024


def test_the_shipped_stylesheets_stay_under_the_size_budget():
    size = shipped_size()
    assert size <= MAX_SHIPPED_BYTES, (
        f"أنماطُ المنصّة المصغَّرةُ صارت {size:,} بايت — تتجاوز السقف {MAX_SHIPPED_BYTES:,} "
        "(260KB). إن كان النموّ مبرَّراً (ميزةٌ فعليّة لا تكرار) فارفع "
        "السقف هنا صراحةً مع سببٍ في رسالة الإيداع؛ لا تُسكِت الحارس بحذفه."
    )


def test_the_budget_measures_what_ships_not_the_commented_source():
    """لو قِيس المصدرُ لعوقبت التعليقاتُ العربيّةُ التي تبرّر القرارات."""
    assert shipped_size() < css_size() * 0.7
