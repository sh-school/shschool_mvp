"""سقفٌ صريحٌ لحجم أنماط المنصّة — نموٌّ يُراقَب لا نموٌّ صامت.

الأنماطُ مصدرٌ واحدٌ للهويّة البصريّة (ثمانيةُ ملفّاتٍ في `static/css/custom/`،
ADR-0003) فتنمو مع كلّ ميزةٍ جديدة — وهذا متوقَّعٌ ومقبول. لكن لا شيء حتى
2026-09-18 كان يُسقط البناءَ عند تجاوزها حجماً بعينه، فالنموُّ يمرّ بصمتٍ حتى
يُكتشَف في تدقيقٍ لاحق.

هذا ليس حظراً على النموّ، بل كابحاً له: تجاوزُ السقف قرارٌ يُرفع صراحةً
(رفعُ السقف نفسِه في هذا الملفّ) لا انزلاقٌ غيرُ مُلاحَظ. والسقفُ 400
كيلوبايت يقيس **مجموعَ** الملفّات (397,008 بايت يومَ التقسيم)، ويُخفَّض
تدريجياً بعد أيّ خطوة تصغير/ضغط فعليّة (خطّة إصلاح الهويّة البصريّة، المرحلة 3).
"""

from tests.css_source import css_size

#: كيلوبايت = 1024 بايت هنا (لا 1000) — قياسُ حجم الملفّات على القرص لا الشبكة.
MAX_BYTES = 400 * 1024


def test_the_platform_stylesheets_stay_under_the_size_budget():
    size = css_size()
    assert size <= MAX_BYTES, (
        f"أنماطُ المنصّة صارت {size:,} بايت — تتجاوز السقف {MAX_BYTES:,} "
        "(400KB). إن كان النموّ مبرَّراً (ميزةٌ فعليّة لا تكرار) فارفع "
        "السقف هنا صراحةً مع سببٍ في رسالة الإيداع؛ لا تُسكِت الحارس بحذفه."
    )
