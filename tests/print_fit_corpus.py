    out: list[str] = []
    out += [f"{rng.choice(FIRST)} {rng.choice(LAST)}" for _ in range(40)]
    out += [f"{rng.choice(FIRST)} محمد {rng.choice(FIRST)} {rng.choice(LAST)}" for _ in range(20)]
    out += DEPTS
    out += CODES + [f"{rng.choice(CODES)} {rng.choice(CODES)}" for _ in range(6)]
    out += VOWELLED + NUMERIC
    while len(out) < n:
        out.append(
            " ".join(
                rng.choice(WORDS) for _ in range(rng.choice([1, 2, 3, 4, 5, 7, 9, 12, 16, 22, 27]))
            )
        )
    return out[:n]
